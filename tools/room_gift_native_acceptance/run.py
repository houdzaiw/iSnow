#!/usr/bin/env python3
"""Run the production room players in an isolated Android app, without login."""

import argparse
import os
import pathlib
import re
import shutil
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(__file__).resolve().parent
FLUTTER = pathlib.Path('/usr/local/flutter/bin/flutter')


def execute(args, cwd=None, env=None):
    subprocess.run([str(arg) for arg in args], cwd=cwd, check=True, env=env)


def locked_version(name):
    text = (ROOT / 'pubspec.lock').read_text()
    block = re.search(r'(?ms)^  ' + re.escape(name) + r':\n(.*?)(?=^  \S|\Z)', text)
    return re.search(r'(?m)^    version: "([^"]+)"', block[1])[1]


def prepare(workspace):
    marker = workspace / '.isnow-native-qa-owned'
    if not (workspace / 'pubspec.yaml').exists():
        execute([FLUTTER, 'create', '--platforms=android', '--no-pub',
                 '--project-name=room_gift_native_acceptance', '--org=com.isnow.qa',
                 workspace])
        marker.write_text('Generated temporary room-player QA workspace\n')
    elif not marker.exists():
        raise RuntimeError('Refusing to modify a workspace not generated by this QA tool')
    expected = 'com.isnow.qa.room_gift_native_acceptance'
    config = workspace / 'android/app/build.gradle.kts'
    if expected not in config.read_text():
        raise RuntimeError('Refusing to use a workspace with a different applicationId')
    manifest = workspace / 'android/app/src/main/AndroidManifest.xml'
    manifest_text = manifest.read_text()
    manifest_text = re.sub(r'\s*<activity android:name="\.CoverActivity"[^>]*/>', '', manifest_text)
    manifest.write_text(manifest_text)

    production = workspace / 'lib/production'
    if production.is_symlink():
        production.unlink()
    elif production.exists():
        raise RuntimeError('Refusing to replace an existing production directory')
    production.symlink_to(ROOT / 'lib', target_is_directory=True)
    fixture = workspace / 'assets/qa'
    fixture.mkdir(parents=True, exist_ok=True)
    for source, target in [
        (ROOT / 'test/fixtures/room_gift_sample.svga', fixture / 'sample.svga'),
        (pathlib.Path('/Users/huili/nady/assets/animations/luck_gift.svga'),
         fixture / 'sample_visual.svga'),
        (ROOT / 'assets/room_gift/combo_button_animation.pag', fixture / 'sample.pag'),
        (pathlib.Path('/Users/huili/nady/assets/animations/bg_lucky_bag_open.mp4'),
         fixture / 'sample_vap.mp4'),
    ]:
        shutil.copyfile(source, target)
    for name in ['room_icon_missing.png', 'room_mini_close.webp']:
        destination = workspace / 'assets/lanhu/room' / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / 'assets/lanhu/room' / name, destination)
    # Use the shipping lucky resources unchanged; this app has no order API.
    lucky_assets = workspace / 'assets/room_gift'
    lucky_assets.mkdir(parents=True, exist_ok=True)
    for source in sorted((ROOT / 'assets/room_gift').glob('luck_num*.mp4')):
        shutil.copyfile(source, lucky_assets / source.name)
    for size in ['small', 'medium', 'big']:
        source = ROOT / 'assets/room_gift' / f'luck_win_{size}.mp4'
        shutil.copyfile(source, lucky_assets / source.name)
    execute(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
             '-f', 'lavfi', '-i', 'testsrc2=size=160x240:rate=24',
             '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100',
             '-t', '2', '-c:v', 'libx264', '-pix_fmt', 'yuv420p',
             '-c:a', 'aac', '-movflags', '+faststart', fixture / 'sample.mp4'])
    execute(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
             '-f', 'lavfi', '-i', 'color=white:size=160x240:rate=8',
             '-f', 'lavfi', '-i', 'testsrc2=size=160x240:rate=8',
             '-filter_complex', '[0:v][1:v]hstack=inputs=2[v]', '-map', '[v]',
             '-t', '23', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-an',
             fixture / 'long_loop_vap.mp4'])

    dependencies = ['cached_network_image', 'flutter_cache_manager',
                    'flutter_screenutil', 'hooks_riverpod', 'intl',
                    'path_provider', 'video_player']
    lines = ["name: room_gift_native_acceptance", "publish_to: none",
             "environment:", "  sdk: ^3.9.2", "dependencies:",
             "  flutter:", "    sdk: flutter"]
    lines += [f'  {name}: {locked_version(name)}' for name in dependencies]
    for name, directory in [('pag', 'room_pag'),
                            ('svgaplayer_flutter', 'room_svga'),
                            ('flutter_vap_plus', 'room_vap')]:
        lines += [f'  {name}:', f'    path: {ROOT / "packages" / directory}']
    lines += ['dev_dependencies:', '  flutter_test:', '    sdk: flutter',
              '  integration_test:', '    sdk: flutter', 'flutter:',
              '  uses-material-design: true', '  assets:',
              '    - assets/qa/', '    - assets/lanhu/room/',
              '    - assets/room_gift/']
    (workspace / 'pubspec.yaml').write_text('\n'.join(lines) + '\n')
    (workspace / 'analysis_options.yaml').write_text(
        'analyzer:\n  exclude:\n    - lib/production/**\n')
    shutil.rmtree(workspace / 'test', ignore_errors=True)
    (workspace / 'lib/main.dart').write_text(
        "import 'package:flutter/widgets.dart';\n"
        'void main() => runApp(const SizedBox.shrink());\n')
    for source, target in [('environment.dart.template', 'integration_test/environment.dart'),
                           ('players_test.dart.template', 'integration_test/players_test.dart'),
                           ('barrage_checks.dart.template', 'integration_test/barrage_checks.dart'),
                           ('visibility_checks.dart.template', 'integration_test/visibility_checks.dart'),
                           ('local_assets_checks.dart.template', 'integration_test/local_assets_checks.dart'),
                           ('combination_checks.dart.template', 'integration_test/combination_checks.dart'),
                           ('combination_scene.dart.template', 'integration_test/combination_scene.dart'),
                           ('main_activity.kt.template', 'android/app/src/main/kotlin/com/isnow/qa/room_gift_native_acceptance/MainActivity.kt'),
                           ('driver.dart.template', 'test_driver/native_driver.dart')]:
        destination = workspace / target
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(HERE / source, destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--device', default='emulator-5554')
    parser.add_argument('--workspace', type=pathlib.Path,
                        default=pathlib.Path('/tmp/isnow_room_gift_native_acceptance'))
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--case', help='Run only native checks whose name contains this text')
    args = parser.parse_args()
    prepare(args.workspace)
    try:
        execute([FLUTTER, 'pub', 'get', '--offline'], args.workspace)
    except subprocess.CalledProcessError:
        execute([FLUTTER, 'pub', 'get'], args.workspace)
    if not args.prepare_only:
        command = [FLUTTER, 'drive', '--no-pub', '-d', args.device,
                 '--keep-app-running',
                 '--driver=test_driver/native_driver.dart',
                 '--target=integration_test/players_test.dart']
        if args.case:
            command.append(f'--dart-define=NATIVE_CASE_FILTER={args.case}')
        env = os.environ.copy()
        env['NATIVE_QA_ADB'] = '/Users/huili/Library/Android/sdk/platform-tools/adb'
        env['NATIVE_QA_DEVICE'] = args.device
        execute(command, args.workspace, env=env)
    print(f'Native QA workspace: {args.workspace}', flush=True)


if __name__ == '__main__':
    main()
